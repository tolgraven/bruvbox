import { readFile, mkdir, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { loadTheme, root } from '../src/theme.mjs';
import { renderCSS, renderSCSS, renderLegacy, renderTerminals, renderPreview, toLua, highlights } from '../src/render.mjs';

const args = process.argv.slice(2);
let output = root, check = false, reportOnly = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--check') check = true;
  else if (args[i] === '--contrast') reportOnly = true;
  else if (args[i] === '--out' && args[i+1] && !args[i+1].startsWith('--')) output = path.resolve(args[++i]);
  else throw new Error(`Unknown or incomplete option: ${args[i]}`);
}
const theme = await loadTheme();
const report = Object.fromEntries(Object.entries(theme.variants).map(([name,v])=>[name,Object.fromEntries(Object.entries(v.combinations).map(([key,c])=>[key,{foreground:c.foreground,background:c.background,ratio:Number(c.contrast.toFixed(3)),normalTextAA:c.contrast>=4.5,largeTextAA:c.contrast>=3}]))]));
if (reportOnly) {
  console.log(JSON.stringify(report,null,2));
} else {
  const adapter = JSON.parse(await readFile(new URL('../adapters/nvim.json',import.meta.url),'utf8'));
  const base16 = JSON.parse(await readFile(new URL('../adapters/base16.json',import.meta.url),'utf8'));
  const highlightPalette = JSON.parse(await readFile(new URL('../adapters/highlight-palette.json',import.meta.url),'utf8'));
  const generated = {};
  const clojurePalettes = {};
  const files = {
    'dist/web/bruvbox.css':renderCSS(theme),
    'dist/web/_bruvbox.scss':renderSCSS(theme),
    'dist/contrast.json':JSON.stringify(report,null,2)+'\n',
    'dist/preview.html':renderPreview(theme),
    'autoload/bruvbox/palette.vim':renderLegacy(theme),
  };
  for (const [name,v] of Object.entries(theme.variants)) {
    clojurePalettes[name] = Object.fromEntries(Object.entries(highlightPalette).map(([key,token]) => {
      if (!v.colors[token]) throw new Error(`Unknown Highlight.js palette token ${token}`);
      return [key,v.colors[token]];
    }));
    generated[name] = {colors:v.colors, combinations:v.combinations, highlights:highlights(v,adapter)};
    files[`dist/json/bruvbox-${name}.json`] = JSON.stringify({schemaVersion:1,name,colors:v.colors,combinations:v.combinations},null,2)+'\n';
    // Standalone DTCG file: all aliases are resolvable within this document.
    const dtcg = structuredClone(theme.paletteDocument);
    for (const [key,token] of Object.entries(v.tokens)) {
      const parts=key.split('.'); let node=dtcg;
      for (const part of parts.slice(0,-1)) node=node[part]??={};
      node[parts.at(-1)]=token;
    }
    dtcg.combination=Object.fromEntries(Object.entries(v.combinationReferences).map(([key,c])=>[key,Object.fromEntries(['foreground','background','border','accent'].filter(k=>c[k]).map(k=>[k,{$type:'color',$value:c[k]}]))]));
    files[`dist/dtcg/bruvbox-${name}.tokens.json`] = JSON.stringify(dtcg,null,2)+'\n';
    Object.assign(files,renderTerminals(v,name,base16));
  }
  files['dist/clojure/bruvbox/theme.cljc'] = '; Generated by scripts/build.mjs. Do not edit.\n(ns bruvbox.theme)\n\n(def highlight-palettes\n  {' + Object.entries(clojurePalettes).map(([name,palette]) => `:${name} {` + Object.entries(palette).map(([key,value])=>`:${key} ${JSON.stringify(value)}`).join('\n           ') + '}').join('\n   ') + '})\n';
  files['lua/bruvbox/generated.lua'] = '-- Generated by scripts/build.mjs. Do not edit.\nreturn '+toLua(generated)+'\n';
  // Detect obsolete artifacts as well as changed/missing ones. Never delete unknown files.
  async function walk(dir) {
    try { return (await Promise.all((await readdir(path.join(output,dir),{withFileTypes:true})).map(e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]))).flat(); }
    catch (error) { if(error.code==='ENOENT') return []; throw error; }
  }
  const stale=(await walk('dist')).filter(p=>!Object.hasOwn(files,p));
  if(stale.length) throw new Error(`Unrecognized generated artifacts; review and remove: ${stale.join(', ')}`);
  const changed=[];
  for (const [file,contents] of Object.entries(files)) {
    const target=path.join(output,file);
    if(check) {
      let actual; try{actual=await readFile(target,'utf8');}catch(error){if(error.code!=='ENOENT') throw error;}
      if(actual!==contents) changed.push(file);
    } else { await mkdir(path.dirname(target),{recursive:true}); await writeFile(target,contents); }
  }
  if(changed.length) throw new Error(`Generated files are out of date: ${changed.join(', ')}. Run npm run build.`);
  console.log(`${check?'Verified':'Generated'} ${Object.keys(files).length} files; ${Object.keys(theme.paletteTokens).length} palette colors; ${Object.keys(theme.variants).length} variants.`);
}
